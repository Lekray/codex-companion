function verifyOriginalFixture(originalDir) {
  const dir = path.resolve(originalDir || DEFAULT_ORIGINAL_DIR);
  const texts = {};
  const hashes = {};
  for (const file of FIXTURE_FILES) {
    const abs = path.join(dir, file);
    if (!fs.existsSync(abs)) {
      throw new Error(`original fixture is missing ${file}: ${abs}`);
    }
    const buf = fs.readFileSync(abs);
    const hash = sha256(buf);
    const expected = SUPPORTED_ORIGINAL_HASHES[file];
    if (hash !== expected) {
      throw new Error(
        `original fixture ${file} has unknown bytes (${hash}); expected the supported original ${expected}`
      );
    }
    texts[file] = buf.toString("utf8");
    hashes[file] = hash;
  }
  return { dir, texts, hashes };
}

function buildMaterials(originalDir) {
  const fixture = verifyOriginalFixture(originalDir);
  const core = loadTitleCoreSource();
  const baselineTexts = {};
  const baselineHashes = {};
  const titleTexts = {};
  const titleHashes = {};

  for (const file of PATCHED_FILES) {
    const baseline = historyPatcher.generatePatchedText(file, fixture.texts[file]);
    if (file === "out/extension.js") {
      for (const marker of ["__companionStartupWatchdog", "__companionHistoryRoots", "companion-history-scope-changed"]) {
        if (!baseline.includes(marker)) {
          throw new Error(`generated history baseline for ${file} is missing ${marker}`);
        }
      }
    } else if (!baseline.includes("companion-history-scope-changed")) {
      throw new Error(`generated history baseline for ${file} is missing companion-history-scope-changed`);
    }
    const title = generatePatchedText(file, baseline, core);
    baselineTexts[file] = baseline;
    baselineHashes[file] = sha256(baseline);
    titleTexts[file] = title;
    titleHashes[file] = sha256(title);
  }

  return { fixture, core, baselineTexts, baselineHashes, titleTexts, titleHashes };
}

