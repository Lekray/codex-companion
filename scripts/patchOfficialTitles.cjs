// Atomic writes / backups
// ---------------------------------------------------------------------------

function atomicWrite(filePath, data) {
  const dir = path.dirname(filePath);
  const tmp = path.join(dir, `.${path.basename(filePath)}.tmp-${process.pid}-${Date.now()}`);
  fs.writeFileSync(tmp, data);
  try {
    fs.renameSync(tmp, filePath);
  } catch (e) {
    try {
      fs.unlinkSync(tmp);
    } catch (_) {}
    throw e;
  }
}

function backupFilePath(backupDir, file) {
  return path.join(backupDir, "files", file);
}

function ensureBaselineBackup(backupDir, file, baselineBytes, baselineSha) {
  const target = backupFilePath(backupDir, file);
  if (fs.existsSync(target)) {
    const existing = sha256(fs.readFileSync(target));
    if (existing !== baselineSha) {
      throw new Error(`refusing to overwrite existing title backup for ${file} (unexpected content)`);
    }
    return;
  }
  fs.mkdirSync(path.dirname(target), { recursive: true });
  atomicWrite(target, baselineBytes);
}

function writeTitleBackupManifest(backupDir, materials) {
  const payload = {
    patchedBy: "patchOfficialTitles.cjs",
    extensionVersion: SUPPORTED_VERSION,
    files: PATCHED_FILES.map((file) => ({
      file,
      preTitleSha: materials.baselineHashes[file],
      patchedSha: materials.titleHashes[file],
    })),
  };
  atomicWrite(path.join(backupDir, "manifest.json"), JSON.stringify(payload, null, 2) + "\n");
}

