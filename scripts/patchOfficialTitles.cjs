const PREVIEW_TITLE_ANCHOR = "this.isPanelAlive(r)&&(r.title=TKe(l))";

function generatePatchedText(file, baselineText, coreSource) {
  const core = coreSource === undefined ? loadTitleCoreSource() : coreSource;

  if (file === "out/extension.js") {
    if (!baselineText.includes("__companionStartupWatchdog") || !baselineText.includes("__companionHistoryRoots")) {
      throw new Error("extension.js: accepted history + watchdog baseline is missing");
    }
    if (baselineText.includes('case"companion-tab-title"')) {
      throw new Error("extension.js: title patch is already present");
    }
    let t = baselineText;
    t = replaceOnce(
      t,
      TKE_ANCHOR,
      TKE_ANCHOR + "\n" + core + "\n" + TITLE_HOST_GLUE,
      "extension.js:inject title helpers after TKe"
    );
    t = replaceOnce(
      t,
      VIEW_FOCUSED_ANCHOR,
      'case"companion-tab-title":{__companionApplyCompanionTabTitle(this,e,r);break}' + VIEW_FOCUSED_ANCHOR,
      "extension.js:handle companion-tab-title"
    );
    t = replaceOnce(
      t,
      PREVIEW_TITLE_ANCHOR,
      "this.isPanelAlive(r)&&__companionShouldApplyPreviewTitle(this,r)&&(r.title=TKe(l))",
      "extension.js:guard stale preview title"
    );
    return t;
  }

  if (file === "webview/assets/app-initial-c014f9ee4429.js") {
    if (!baselineText.includes("companion-history-scope-changed")) {
      throw new Error("c014 bundle: accepted history baseline is missing");
    }
    if (baselineText.includes("companion-tab-title")) {
      throw new Error("c014 bundle: title patch is already present");
    }
    return replaceOnce(
      baselineText,
      C014_SEAM,
      C014_SEAM_REPLACEMENT,
      "c014:report local thread title from router"
    );
  }

  throw new Error(`not a patched file: ${file}`);
}

