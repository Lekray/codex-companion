function readExtensionPackage(extDir) {
  const pkgPath = path.join(extDir, "package.json");
  if (!fs.existsSync(pkgPath)) throw new Error(`package.json not found in ${extDir}`);
  return JSON.parse(fs.readFileSync(pkgPath, "utf8"));
}

function verifyExtensionIdentity(extDir) {
  const pkg = readExtensionPackage(extDir);
  const errors = [];
  if (pkg.publisher !== PUBLISHER) errors.push(`publisher ${JSON.stringify(pkg.publisher)} !== ${PUBLISHER}`);
  if (pkg.name !== NAME) errors.push(`name ${JSON.stringify(pkg.name)} !== ${NAME}`);
  if (pkg.version !== SUPPORTED_VERSION) {
    errors.push(`version ${JSON.stringify(pkg.version)} !== ${JSON.stringify(SUPPORTED_VERSION)}`);
  }
  return { ok: errors.length === 0, errors, pkg };
}

function computePlan(extDir, originalDir) {
  const materials = buildMaterials(originalDir);
  const identity = verifyExtensionIdentity(extDir);

  const pkgPath = path.join(extDir, "package.json");
  let packageJson;
  if (!fs.existsSync(pkgPath)) {
    packageJson = {
      exists: false,
      current: null,
      original: SUPPORTED_ORIGINAL_HASHES["package.json"],
      length: null,
      status: "missing",
    };
  } else {
    const buf = fs.readFileSync(pkgPath);
    const current = sha256(buf);
    const original = SUPPORTED_ORIGINAL_HASHES["package.json"];
    packageJson = {
      exists: true,
      current,
      original,
      length: buf.length,
      status: current === original ? "original" : "mismatch",
    };
  }

  const files = {};
  for (const file of PATCHED_FILES) {
    const abs = path.join(extDir, file);
    const originalSha = materials.fixture.hashes[file];
    const baselineSha = materials.baselineHashes[file];
    const patchedSha = materials.titleHashes[file];
    if (!fs.existsSync(abs)) {
      files[file] = { status: "missing", originalSha, baselineSha, patchedSha, currentSha: null, length: null };
      continue;
    }
    const buf = fs.readFileSync(abs);
    const currentSha = sha256(buf);
    let status;
    if (currentSha === originalSha) status = "original";
    else if (currentSha === baselineSha) status = "baseline";
    else if (currentSha === patchedSha) status = "patched";
    else status = "foreign";
    files[file] = { status, originalSha, baselineSha, patchedSha, currentSha, length: buf.length };
  }

  return { materials, identity, packageJson, files };
}

function aggregateCheckStatus(identity, packageJson, files) {
  if (!identity.ok) return "identity-error";
  if (packageJson.status !== "original") return `package-json-${packageJson.status}`;
  const values = PATCHED_FILES.map((file) => files[file].status);
  if (values.includes("missing")) return "missing";
  if (values.includes("foreign")) return "foreign";
  if (values.every((s) => s === "original")) return "original";
  if (values.every((s) => s === "baseline")) return "baseline";
  if (values.every((s) => s === "patched")) return "patched";
  if (values.every((s) => s === "baseline" || s === "patched")) return "mixed";
  return "unknown";
}

function publicFileDetail(fileEntry) {
  return {
    status: fileEntry.status,
    originalSha: fileEntry.originalSha,
    baselineSha: fileEntry.baselineSha,
    patchedSha: fileEntry.patchedSha,
    currentSha: fileEntry.currentSha,
    length: fileEntry.length,
  };
}

function checkPatch({ extDir, originalDir }) {
  const full = computePlan(extDir, originalDir);
  const statuses = {};
  const plan = {};
  for (const file of PATCHED_FILES) {
    statuses[file] = full.files[file].status;
    plan[file] = publicFileDetail(full.files[file]);
  }
  return {
    command: "check",
    identityOk: full.identity.ok,
    identityErrors: full.identity.errors,
    version: SUPPORTED_VERSION,
    status: aggregateCheckStatus(full.identity, full.packageJson, full.files),
    packageJson: full.packageJson.status,
    files: statuses,
    detail: { packageJson: full.packageJson, plan },
    originalDir: full.materials.fixture.dir,
  };
}

