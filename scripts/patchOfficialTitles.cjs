// check / apply / restore
// ---------------------------------------------------------------------------

function applyPatch({ extDir, backupDir, originalDir }) {
  const full = computePlan(extDir, originalDir);
  if (!full.identity.ok) throw new Error(`identity check failed: ${full.identity.errors.join("; ")}`);
  if (full.packageJson.status !== "original") {
    throw new Error(
      `package.json does not match the supported original hash (${full.packageJson.status}); refusing to apply`
    );
  }

  // All-file preflight before any write or backup creation.
  const toPatch = [];
  for (const file of PATCHED_FILES) {
    const status = full.files[file].status;
    if (status === "patched") continue;
    if (status !== "baseline") {
      throw new Error(`${file} is not in the accepted pre-title baseline (${status}); refusing`);
    }
    toPatch.push(file);
  }
  if (toPatch.length === 0) {
    return {
      command: "apply",
      version: SUPPORTED_VERSION,
      applied: [],
      files: Object.fromEntries(PATCHED_FILES.map((file) => [file, "patched"])),
      backupDir,
    };
  }

  // Back up the computed pre-title bytes (never trust the current bytes alone).
  for (const file of PATCHED_FILES) {
    ensureBaselineBackup(
      backupDir,
      file,
      Buffer.from(full.materials.baselineTexts[file], "utf8"),
      full.materials.baselineHashes[file]
    );
  }

  const written = [];
  try {
    for (const file of toPatch) {
      const abs = path.join(extDir, file);
      const beforeBytes = fs.readFileSync(abs);
      const titleText = full.materials.titleTexts[file];
      if (sha256(titleText) !== full.files[file].patchedSha) {
        throw new Error(`internal error: patched digest mismatch for ${file}`);
      }
      atomicWrite(abs, titleText);
      written.push({ file, abs, beforeBytes });
    }
    writeTitleBackupManifest(backupDir, full.materials);
  } catch (e) {
    const rollbackErrors = [];
    for (const entry of written.reverse()) {
      try {
        atomicWrite(entry.abs, entry.beforeBytes);
      } catch (re) {
        rollbackErrors.push(`${entry.file}: ${re.message || re}`);
      }
    }
    throw new Error(
      `apply failed: ${e.message || e}${rollbackErrors.length ? `; rollback errors: ${rollbackErrors.join("; ")}` : ""}`
    );
  }

  return {
    command: "apply",
    version: SUPPORTED_VERSION,
    applied: written.map((entry) => entry.file),
    files: Object.fromEntries(PATCHED_FILES.map((file) => [file, "patched"])),
    backupDir,
  };
}

function restorePatch({ extDir, backupDir, originalDir }) {
  const full = computePlan(extDir, originalDir);
  if (!full.identity.ok) throw new Error(`identity check failed: ${full.identity.errors.join("; ")}`);
  if (full.packageJson.status !== "original") {
    throw new Error(
      `package.json does not match the supported original hash (${full.packageJson.status}); refusing to restore`
    );
  }

  // All-file preflight: every current file must be baseline or patched, and every
  // needed backup must contain exactly the verified pre-title baseline.
  const actions = [];
  for (const file of PATCHED_FILES) {
    const entry = full.files[file];
    if (entry.status === "baseline") continue;
    if (entry.status !== "patched") {
      throw new Error(`${file}: current bytes are neither pre-title baseline nor title-patched (${entry.status}); refusing`);
    }
    const backupAbs = backupFilePath(backupDir, file);
    if (!fs.existsSync(backupAbs)) {
      throw new Error(`${file}: pre-title backup missing at ${backupAbs}; cannot restore safely`);
    }
    const backupBytes = fs.readFileSync(backupAbs);
    if (sha256(backupBytes) !== entry.baselineSha) {
      throw new Error(`${file}: pre-title backup bytes do not match the verified baseline; refusing`);
    }
    actions.push({ file, abs: path.join(extDir, file), backupBytes, beforeBytes: fs.readFileSync(path.join(extDir, file)) });
  }

  if (actions.length === 0) {
    return {
      command: "restore",
      version: SUPPORTED_VERSION,
      restored: [],
      files: Object.fromEntries(PATCHED_FILES.map((file) => [file, "baseline"])),
      backupDir,
    };
  }

  const written = [];
  try {
    for (const action of actions) {
      atomicWrite(action.abs, action.backupBytes);
      written.push(action);
    }
  } catch (e) {
    const rollbackErrors = [];
    for (const action of written.reverse()) {
      try {
        atomicWrite(action.abs, action.beforeBytes);
      } catch (re) {
        rollbackErrors.push(`${action.file}: ${re.message || re}`);
      }
    }
    throw new Error(
      `restore failed: ${e.message || e}${rollbackErrors.length ? `; rollback errors: ${rollbackErrors.join("; ")}` : ""}`
    );
  }

  return {
    command: "restore",
    version: SUPPORTED_VERSION,
    restored: actions.map((action) => action.file),
    files: Object.fromEntries(PATCHED_FILES.map((file) => [file, "baseline"])),
    backupDir,
  };
}

