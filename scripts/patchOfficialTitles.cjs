/*
 * Version/hash guarded, reversible local title-sync patch for official Codex
 * 26.1007.21434, layered on top of the accepted history + watchdog patch.
 *
 * It changes only two files:
 *   - webview/assets/app-initial-c014f9ee4429.js: report the reactive local
 *     thread title (and local route) to the extension host from the always
 *     mounted router component. Home/remote/settings routes report a reset.
 *   - out/extension.js: apply the title to the exact panel behind the sending
 *     webview (native + custom editor panels), validate the local thread route,
 *     reset chat panels to the native fallback title on home/nonlocal routes,
 *     and prevent the stale async conversation preview from overwriting a live
 *     reported title.
 *
 * API:
 *   node scripts/patchOfficialTitles.cjs check|apply|restore --extension <dir> --backup <dir> [--original-dir <dir>]
 *
 * The baselines (pre-title bytes) are generated by the existing
 * scripts/patchOfficialHistory.cjs. The original fixture is verified against
 * the known original hashes before any baseline/current state is trusted.
 * The patcher never reads an arbitrary manifest.
 */

